package com.nspay.validators;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.RequiredArgsConstructor;

@Getter
@RequiredArgsConstructor
@AllArgsConstructor
public class ValidationResults {//validationResults.getCode() returns the ResponseCode enum value, generated by Lombok e.g ResponseCode.DAILY_TX_LIMIT_EXCEEDED
    private final boolean isValid;
    private boolean isBusinessLogicViolation;
    private final ResponseCode code;
    private final String message;

    public static ValidationResults success(boolean isBusinessLogicViolation, ResponseCode code, String message) {
        return new ValidationResults(true, isBusinessLogicViolation, code, message);
    }

    public static ValidationResults failure(ResponseCode responseCode, String responseMessage) {
        return new ValidationResults(false, false, responseCode, responseMessage);
    }
}
